/**
 * Настройки салона, приходящие из окружения.
 *
 * Читаются в одном месте: разбросанный по коду `process.env` рано или
 * поздно даёт опечатку в имени переменной, которую видно только в проде.
 */

const timeZone = process.env.SALON_TIMEZONE;

if (!timeZone) {
  throw new Error(
    "SALON_TIMEZONE не задан. Скопируйте .env.example в .env — без часового пояса нельзя вычислить рабочие часы.",
  );
}

/** Часовой пояс, в котором салон живёт по настенным часам. */
export const SALON_TIMEZONE = timeZone;

/** Шаг сетки предлагаемых слотов, минуты. */
export const SLOT_STEP_MIN = 30;

/** Минимальный запас перед записью: нельзя прийти «через пять минут». */
export const MIN_LEAD_TIME_MIN = 60;
